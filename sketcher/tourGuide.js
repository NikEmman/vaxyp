            "Αποθηκεύστε το τρέχον σκαρίφημα με ένα όνομα ώστε να συνεχίσετε αργότερα, ή φορτώστε ένα σκαρίφημα που έχετε ήδη αποθηκεύσει. Τα σκαριφήματα αποθηκεύονται τοπικά στον browser σας.",
